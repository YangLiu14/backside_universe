// Regression for rig retention, independent clones and history-free scrubbing.
import assert from 'node:assert/strict';
import * as T from 'three';
import {prepareCampusActor,cloneCampusActor,dressRiggedActor,animateRiggedActor} from './viewer/rigged-actors.js';
const geo=new T.BoxGeometry(.2,.8,.2),n=geo.attributes.position.count;
geo.setAttribute('skinIndex',new T.Uint16BufferAttribute(new Uint16Array(n*4),4));
const weights=new Float32Array(n*4);for(let i=0;i<n;i++)weights[i*4]=1;
geo.setAttribute('skinWeight',new T.Float32BufferAttribute(weights,4));
const hips=new T.Bone();hips.name='Hips';
const neck=new T.Bone();neck.name='Head';neck.position.y=1.3;hips.add(neck);
const mesh=new T.SkinnedMesh(geo,new T.MeshStandardMaterial());mesh.name='Body';mesh.add(hips);mesh.bind(new T.Skeleton([hips,neck]));
const scene=new T.Group();scene.add(mesh);
const clip=new T.AnimationClip('walk',4,[new T.VectorKeyframeTrack('Hips.position',[0,2,4],[0,0,0,0,.05,1,0,0,2])]);
const metadata={clip:'walk',height:1.6,headBone:'Head',rootBone:'Hips',restHeadMount:[0,1.3,0],removedHeadTriangles:12000};
const body=prepareCampusActor('walker',{scene,animations:[clip]},metadata),copy=cloneCampusActor(body);
assert(body.getObjectByName('Body').isSkinnedMesh);
assert.notEqual(copy.getObjectByName('Body').skeleton,body.getObjectByName('Body').skeleton);
assert.notEqual(copy.getObjectByName('Hips'),body.getObjectByName('Hips'));
const head=()=>{const g=new T.Group();g.userData.native=[.2,.3,.2];g.add(new T.Mesh(new T.BoxGeometry(1,1,1),new T.MeshStandardMaterial()));return g;};
const structure={'walker-head':{neck:[0,-.5,0],faceWidth:.2,removeTriangles:[]},'companion-head':{neck:[0,-.5,0],faceWidth:.2,removeTriangles:[]}};
dressRiggedActor(body,head(),'walker',structure);dressRiggedActor(copy,head(),'walker',structure,1);
const point=actor=>{const m=actor.getObjectByName('Body');return m.localToWorld(m.getVertexPosition(0,new T.Vector3())).toArray();};
animateRiggedActor(body,.8);const expected=point(body);
for(const t of [4,0,3.2,1.5,4,.8])animateRiggedActor(body,t);
assert.deepEqual(point(body),expected,'Direct sample is independent of prior finish/rewind history');
animateRiggedActor(copy,2.4);assert.deepEqual(point(body),expected,'Another actor has independent bones');
assert.notDeepEqual(point(copy),expected);
assert.throws(()=>prepareCampusActor('walker',{scene:new T.Group(),animations:[]},metadata),/蒙皮/);
const bad=prepareCampusActor('shooter',{scene,animations:[clip]}, {...metadata,duration:8});
assert.throws(()=>dressRiggedActor(bad,head(),'walker',structure),/时长/,'Reject an older same-name clip with a mismatched exported clock');
console.log('PASS: retained skin, independent skeletons, deterministic end-to-rewind sampling and exported clip duration');
